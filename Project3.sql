//PHASE_7: Task Automation 
//Task_25: Create a Task that automatically performs incremental loading every day.

CREATE OR REPLACE TASK DAILY_INCREMENTAL_LOAD
    WAREHOUSE = ENTERPRISE_WH
    SCHEDULE = 'USING CRON 0 0 * * * UTC'
    WHEN SYSTEM$STREAM_HAS_DATA('SALES_STREAM')
AS
    MERGE INTO SALES AS TARGET
    USING (
        SELECT
            SALE_ID,
            CUSTOMER_ID,
            PRODUCT_ID,
            BRANCH_ID,
            QUANTITY,
            SALE_DATE,
            TOTAL_AMOUNT
        FROM SALES_STREAM
    ) AS SOURCE
    ON TARGET.SALE_ID = SOURCE.SALE_ID

    WHEN MATCHED THEN
        UPDATE SET
            TARGET.CUSTOMER_ID = SOURCE.CUSTOMER_ID,
            TARGET.PRODUCT_ID = SOURCE.PRODUCT_ID,
            TARGET.BRANCH_ID = SOURCE.BRANCH_ID,
            TARGET.QUANTITY = SOURCE.QUANTITY,
            TARGET.SALE_DATE = SOURCE.SALE_DATE,
            TARGET.TOTAL_AMOUNT = SOURCE.TOTAL_AMOUNT

    WHEN NOT MATCHED THEN
        INSERT (
            SALE_ID,
            CUSTOMER_ID,
            PRODUCT_ID,
            BRANCH_ID,
            QUANTITY,
            SALE_DATE,
            TOTAL_AMOUNT
        )
        VALUES (
            SOURCE.SALE_ID,
            SOURCE.CUSTOMER_ID,
            SOURCE.PRODUCT_ID,
            SOURCE.BRANCH_ID,
            SOURCE.QUANTITY,
            SOURCE.SALE_DATE,
            SOURCE.TOTAL_AMOUNT
        );

//Task_26: Resume the task 
ALTER TASK DAILY_INCREMENTAL_LOAD RESUME;

//Task_27: Verify Task execution

SELECT
    NAME,
    STATE,
    SCHEDULED_TIME,
    COMPLETED_TIME,
    QUERY_ID,
    ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY())
WHERE NAME = 'DAILY_INCREMENTAL_LOAD'
ORDER BY SCHEDULED_TIME DESC;

