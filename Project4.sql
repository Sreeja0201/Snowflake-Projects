JOIN DIM_BRANCH B
    ON F.BRANCH_ID = B.BRANCH_ID
GROUP BY
    B.BRANCH_NAME,
    B.STATE,
    B.REGION
ORDER BY REVENUE DESC;

//Task 39: Complete Star Schema Query

SELECT
    F.SALE_ID,

    C.CUSTOMER_NAME,
    C.MEMBERSHIP,

    P.PRODUCT_NAME,
    P.CATEGORY,
    P.BRAND,

    B.BRANCH_NAME,
    B.CITY AS BRANCH_CITY,
    B.STATE AS BRANCH_STATE,
    B.REGION,

    D.DATE,
    D.MONTH,
    D.QUARTER,
    D.YEAR,

    F.QUANTITY,
    F.TOTAL_AMOUNT

FROM FACT_SALES F

JOIN DIM_CUSTOMER C
    ON F.CUSTOMER_ID = C.CUSTOMER_ID

JOIN DIM_PRODUCT P
    ON F.PRODUCT_ID = P.PRODUCT_ID

JOIN DIM_BRANCH B
    ON F.BRANCH_ID = B.BRANCH_ID

JOIN DIM_DATE D
    ON F.DATE_ID = D.DATE_ID

ORDER BY F.SALE_ID;

