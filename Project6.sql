SELECT
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    city.CITY_NAME,
    s.STATE_NAME,
    r.REGION_NAME,
    SUM(f.QUANTITY) AS TOTAL_QUANTITY,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_CUSTOMER c
    ON f.CUSTOMER_ID = c.CUSTOMER_ID
JOIN DIM_CITY city
    ON c.CITY_ID = city.CITY_ID
JOIN DIM_STATE s
    ON city.STATE_ID = s.STATE_ID
JOIN DIM_REGION r
    ON s.REGION_ID = r.REGION_ID
GROUP BY
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    city.CITY_NAME,
    s.STATE_NAME,
    r.REGION_NAME
ORDER BY c.CUSTOMER_ID;

SELECT
    p.PRODUCT_ID,
    p.PRODUCT_NAME,
    b.BRAND_NAME,
    c.CATEGORY_NAME,
    SUM(f.QUANTITY) AS TOTAL_QUANTITY,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_PRODUCT p
    ON f.PRODUCT_ID = p.PRODUCT_ID
JOIN DIM_BRAND b
    ON p.BRAND_ID = b.BRAND_ID
JOIN DIM_CATEGORY c
    ON b.CATEGORY_ID = c.CATEGORY_ID
GROUP BY
    p.PRODUCT_ID,
    p.PRODUCT_NAME,
    b.BRAND_NAME,
    c.CATEGORY_NAME
ORDER BY p.PRODUCT_ID;

SELECT
    b.BRANCH_ID,
    b.BRANCH_NAME,
    city.CITY_NAME,
    s.STATE_NAME,
    r.REGION_NAME,
    SUM(f.QUANTITY) AS TOTAL_QUANTITY,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_BRANCH b
    ON f.BRANCH_ID = b.BRANCH_ID
JOIN DIM_CITY city
    ON b.CITY_ID = city.CITY_ID
JOIN DIM_STATE s
    ON city.STATE_ID = s.STATE_ID
JOIN DIM_REGION r
    ON s.REGION_ID = r.REGION_ID
