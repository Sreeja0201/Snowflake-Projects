//Task_31: Rank Customers Based on Total Spending
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_SPENDING,
    RANK() OVER (
        ORDER BY SUM(S.TOTAL_AMOUNT) DESC
    ) AS CUSTOMER_RANK
FROM CUSTOMERS C
JOIN SALES S
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME
ORDER BY CUSTOMER_RANK;

//Task_32: Rank Branches Based on Total Sales
SELECT
    B.BRANCH_ID,
    B.BRANCH_NAME,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_SALES,
    RANK() OVER (
        ORDER BY SUM(S.TOTAL_AMOUNT) DESC
    ) AS BRANCH_RANK
FROM BRANCHES B
JOIN SALES S
    ON B.BRANCH_ID = S.BRANCH_ID
GROUP BY
    B.BRANCH_ID,
    B.BRANCH_NAME
ORDER BY BRANCH_RANK;

//Task_33: Top-Selling Product in Each Category
WITH PRODUCT_SALES AS (
    SELECT
        P.PRODUCT_ID,
        P.PRODUCT_NAME,
        P.CATEGORY,
        SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE
    FROM PRODUCTS P
    JOIN SALES S
        ON P.PRODUCT_ID = S.PRODUCT_ID
    GROUP BY
        P.PRODUCT_ID,
        P.PRODUCT_NAME,
        P.CATEGORY
),

RANKED_PRODUCTS AS (
    SELECT
        PRODUCT_ID,
        PRODUCT_NAME,
        CATEGORY,
        TOTAL_REVENUE,
        ROW_NUMBER() OVER (
            PARTITION BY CATEGORY
            ORDER BY TOTAL_REVENUE DESC
        ) AS RN
    FROM PRODUCT_SALES
)

SELECT
    PRODUCT_ID,
    PRODUCT_NAME,
    CATEGORY,
    TOTAL_REVENUE
FROM RANKED_PRODUCTS
WHERE RN = 1
ORDER BY CATEGORY;

//Task_34: Calculate Cumulative Sales
SELECT
    SALE_ID,
    SALE_DATE,
    TOTAL_AMOUNT,
    SUM(TOTAL_AMOUNT) OVER (
        ORDER BY SALE_DATE, SALE_ID
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS CUMULATIVE_SALES
FROM SALES
ORDER BY SALE_DATE, SALE_ID;

//Task_35: Calculate Average Sale Amount Using AVG() OVER()
SELECT
    SALE_ID,
    SALE_DATE,
    TOTAL_AMOUNT,
    AVG(TOTAL_AMOUNT) OVER () AS AVERAGE_SALE_AMOUNT
FROM SALES
ORDER BY SALE_ID;

//Phase 5
//Task_36: Customer-wise Revenue Using CTE
WITH CUSTOMER_REVENUE AS (
    SELECT
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME,
        SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE
    FROM CUSTOMERS C
    JOIN SALES S
        ON C.CUSTOMER_ID = S.CUSTOMER_ID
    GROUP BY
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME
)

SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    TOTAL_REVENUE
FROM CUSTOMER_REVENUE
ORDER BY TOTAL_REVENUE DESC;

//Task_37: Customers Spending Greater Than Average
WITH CUSTOMER_SPENDING AS (
    SELECT
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME,
        SUM(S.TOTAL_AMOUNT) AS TOTAL_SPENDING
    FROM CUSTOMERS C
    JOIN SALES S
        ON C.CUSTOMER_ID = S.CUSTOMER_ID
    GROUP BY
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME
),

AVERAGE_SPENDING AS (
    SELECT
        AVG(TOTAL_SPENDING) AS AVG_SPENDING
    FROM CUSTOMER_SPENDING
)

SELECT
    CS.CUSTOMER_ID,
    CS.CUSTOMER_NAME,
    CS.TOTAL_SPENDING
FROM CUSTOMER_SPENDING CS
CROSS JOIN AVERAGE_SPENDING A
WHERE CS.TOTAL_SPENDING > A.AVG_SPENDING
ORDER BY CS.TOTAL_SPENDING DESC;

//Phase 6
//Task_38: Create SALES_REPORT View
CREATE OR REPLACE VIEW SALES_REPORT AS
SELECT
    S.SALE_ID,
    S.SALE_DATE,

    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.MEMBERSHIP,

    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    P.CATEGORY,
    P.PRICE,

    B.BRANCH_ID,
    B.BRANCH_NAME,
    B.CITY AS BRANCH_CITY,

    S.QUANTITY,
    S.TOTAL_AMOUNT

FROM SALES S

JOIN CUSTOMERS C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID

JOIN PRODUCTS P
    ON S.PRODUCT_ID = P.PRODUCT_ID

JOIN BRANCHES B
    ON S.BRANCH_ID = B.BRANCH_ID;

//Task_39: Query SALES_REPORT
SELECT *
FROM SALES_REPORT
ORDER BY SALE_ID;

//Task_40: Create Materialized View TOP_CUSTOMERS
CREATE OR REPLACE MATERIALIZED VIEW TOP_CUSTOMERS AS
SELECT
    CUSTOMER_ID,
    SUM(TOTAL_AMOUNT) AS TOTAL_SPENDING
FROM SALES
GROUP BY CUSTOMER_ID;

//Task_41: Query Materialized View
SELECT
    TC.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    TC.TOTAL_SPENDING
FROM TOP_CUSTOMERS TC
JOIN CUSTOMERS C
    ON TC.CUSTOMER_ID = C.CUSTOMER_ID
ORDER BY TC.TOTAL_SPENDING DESC;

