//Task_23: Customer wise sales
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CITY,
    C.MEMBERSHIP,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_SALES
FROM CUSTOMERS C
JOIN SALES S
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CITY,
    C.MEMBERSHIP
ORDER BY TOTAL_SALES DESC;

