CREATE OR REPLACE TABLE SNOW_FACT_SALES (
    SALES_KEY        NUMBER AUTOINCREMENT PRIMARY KEY,
    TRANSACTION_ID   VARCHAR(50),
    TRANSACTION_DATE DATE,
    CUSTOMER_ID      NUMBER,
    STORE_KEY        NUMBER REFERENCES SNOW_DIM_STORE(STORE_KEY),
    PRODUCT_KEY      NUMBER REFERENCES SNOW_DIM_PRODUCT(PRODUCT_KEY),
    QUANTITY         NUMBER,
    TOTAL_AMOUNT     NUMBER(12,2)
);

INSERT INTO SNOW_FACT_SALES
    (TRANSACTION_ID, TRANSACTION_DATE, CUSTOMER_ID, STORE_KEY, PRODUCT_KEY, QUANTITY, TOTAL_AMOUNT)
SELECT
    t.transaction_id,
    t.transaction_date,
    t.customer_id,
    s.STORE_KEY,
    p.PRODUCT_KEY,
    t.quantity,
    t.quantity * t.unit_price AS total_amount
FROM (
    SELECT 'TXN-3001' AS transaction_id, '2026-05-01'::DATE AS transaction_date, 101 AS customer_id, 201 AS store_id, 501 AS product_id, 1 AS quantity, 75000.00 AS unit_price
    UNION ALL SELECT 'TXN-3002', '2026-05-02'::DATE, 102, 202, 502, 2, 1500.00
    UNION ALL SELECT 'TXN-3003', '2026-05-03'::DATE, 103, 203, 503, 1, 12000.00
