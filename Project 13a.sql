UNION ALL SELECT 'Snowflake Schema', 'SNOW_DIM_CATEGORY',     COUNT(*) FROM SNOW_DIM_CATEGORY
UNION ALL SELECT 'Snowflake Schema', 'SNOW_DIM_SUBCATEGORY',  COUNT(*) FROM SNOW_DIM_SUBCATEGORY
